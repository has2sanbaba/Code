package code.simurgh.scanner

import com.dokar.quickjs.QuickJs
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.util.Base64

/**
 * Differential tests: the very bundle the app ships (`src/main/assets/engine.js`)
 * runs inside a real QuickJS runtime -- the quickjs-kt JVM artifact, substituted
 * in by app/build.gradle.kts for local unit tests -- and is compared bit for bit
 * against vectors generated by the reference TypeScript core
 * (`node tools/gen-android-vectors.mjs`).
 *
 * No device, no emulator: this is what CI runs before it signs an APK.
 */
class EngineVectorsTest {

    private val vectors: JSONObject by lazy {
        JSONObject(resource("vectors.json").decodeToString())
    }

    private fun resource(name: String): ByteArray =
        javaClass.classLoader!!.getResourceAsStream(name)!!.use { it.readBytes() }

    /** Declared to return Unit so JUnit sees a void method. */
    private fun withEngine(block: suspend (QuickJs) -> Unit) {
        runBlocking {
            val vm = QuickJs.create(Dispatchers.Default)
            try {
                vm.maxStackSize = 8L * 1024 * 1024
                val source = File("src/main/assets/engine.js")
                assertTrue("engine.js missing -- run `npm run engine` first", source.isFile)
                vm.evaluate<Any?>(source.readText(), "engine.js")
                block(vm)
            } finally {
                vm.close()
            }
        }
    }

    private class PgmImage(val width: Int, val height: Int, val data: ByteArray)

    private fun parsePgm(bytes: ByteArray): PgmImage {
        var pos = 0
        fun nextToken(): String {
            while (true) {
                while (pos < bytes.size) {
                    val c = bytes[pos].toInt().toChar()
                    if (c == '#') {
                        while (pos < bytes.size && bytes[pos] != '\n'.code.toByte()) pos++
                    } else if (c.isWhitespace()) {
                        pos++
                    } else {
                        break
                    }
                }
                val start = pos
                while (pos < bytes.size && !bytes[pos].toInt().toChar().isWhitespace()) pos++
                if (pos > start) return String(bytes, start, pos - start, Charsets.US_ASCII)
            }
        }
        assertEquals("P5", nextToken())
        val w = nextToken().toInt()
        val h = nextToken().toInt()
        val maxVal = nextToken().toInt()
        assertEquals(255, maxVal)
        pos++ // exactly one whitespace character separates maxval from the raster
        val data = bytes.copyOfRange(pos, pos + w * h)
        assertEquals(w * h, data.size)
        return PgmImage(w, h, data)
    }

    /* ------------------------------------------------------------------ spec */

    @Test
    fun specIsFrozen() = withEngine { vm ->
        val spec = Engine.callRaw(vm, JSONObject().put("op", "spec"))
        assertEquals("SiMurgh Code", spec.getString("name"))
        assertEquals("SMC", spec.getString("id"))
        assertEquals(vectors.getJSONObject("spec").getString("version"), spec.getString("version"))
        assertEquals(vectors.getJSONObject("spec").getString("date"), spec.getString("date"))
    }

    @Test
    fun themesAreCompleteAndPrintSafe() = withEngine { vm ->
        val themes = Engine.callRaw(vm, JSONObject().put("op", "themes")).getJSONArray("themes")
        assertEquals(8, themes.length())
        for (i in 0 until themes.length()) {
            val t = themes.getJSONObject(i)
            assertTrue(t.getString("id") + " contrast", t.getDouble("contrast") >= 7.0)
            assertTrue(t.getString("id") + " printable", t.getBoolean("printable"))
            assertTrue(t.getString("fa").isNotEmpty())
        }
    }

    /* ------------------------------------------------- encode: bit-exactness */

    @Test
    fun encodeMatchesReferenceBitForBit() = withEngine { vm ->
        val list = vectors.getJSONArray("encode")
        assertTrue(list.length() >= 6)
        for (i in 0 until list.length()) {
            val v = list.getJSONObject(i)
            val name = v.getString("name")
            val req = JSONObject(v.getJSONObject("req").toString()).put("op", "encode")
            val r = Engine.callRaw(vm, req)
            assertTrue("$name: ${r.optString("error")}", r.optBoolean("ok"))
            val e = v.getJSONObject("expect")
            assertEquals(name, e.getInt("version"), r.getInt("version"))
            assertEquals(name, e.getString("ecc"), r.getString("ecc"))
            assertEquals(name, e.getInt("mask"), r.getInt("mask"))
            assertEquals(name, e.getInt("formatWord"), r.getInt("formatWord"))
            assertEquals(name, e.getInt("payloadBytes"), r.getInt("payloadBytes"))
            assertEquals(name, e.getInt("codewords"), r.getInt("codewords"))
            assertEquals(name, e.getString("dataBitsHex"), r.getString("dataBitsHex"))
            assertEquals(name, e.getString("beadsHex"), r.getString("beadsHex"))
        }
    }

    @Test
    fun decodeBitsRoundTripsEveryVector() = withEngine { vm ->
        val list = vectors.getJSONArray("encode")
        for (i in 0 until list.length()) {
            val v = list.getJSONObject(i)
            val name = v.getString("name")
            val e = v.getJSONObject("expect")
            val back = Engine.decodeBitsRaw(vm, e.getString("dataBitsHex"), e.getString("beadsHex"))
            assertTrue("$name: ${back.optString("error")}", back.optBoolean("ok"))
            assertTrue(name + " crc", back.getBoolean("crcOk"))
            assertTrue(name + " text", back.getString("text").isNotEmpty())
        }
    }

    /* ------------------------------------------------- sealed (SECURE) paths */

    @Test
    fun sealedEnvelopesMatchReference() = withEngine { vm ->
        val list = vectors.getJSONArray("secure")
        assertTrue(list.length() >= 3)
        for (i in 0 until list.length()) {
            val v = list.getJSONObject(i)
            val name = v.getString("name")
            val req = JSONObject(v.getJSONObject("req").toString()).put("op", "encode")
            val r = Engine.callRaw(vm, req)
            assertTrue("$name: ${r.optString("error")}", r.optBoolean("ok"))
            val e = v.getJSONObject("expect")
            val secure = r.getJSONObject("secure")
            assertEquals(name, e.getString("keyId"), secure.getString("keyId"))
            assertEquals(name, e.getString("ciphertextHex"), secure.getString("ciphertextHex"))
            assertEquals(name, e.getString("dataBitsHex"), r.getString("dataBitsHex"))

            val dataBits = r.getString("dataBitsHex")
            val beads = r.getString("beadsHex")

            // Opens with the right key.
            val opened =
                Engine.decodeBitsRaw(vm, dataBits, beads, v.getJSONObject("openWith").toString())
            assertTrue("$name open: ${opened.optString("error")}", opened.optBoolean("ok"))
            assertTrue(name + " unlocked", opened.optBoolean("unlocked"))
            assertEquals(name, v.getString("text"), opened.getString("text"))

            // Without any key: structure reads, content does not.
            val locked = Engine.decodeBitsRaw(vm, dataBits, beads)
            assertTrue(name + " locked ok", locked.optBoolean("ok"))
            assertTrue(name + " encrypted", locked.optBoolean("encrypted"))
            assertFalse(name + " locked stays locked", locked.optBoolean("unlocked"))

            // A wrong key is indistinguishable from tampering: stays sealed.
            val wrong = Engine.decodeBitsRaw(vm, dataBits, beads, JSONObject().put("pass", "definitely-wrong").toString())
            assertTrue(name + " wrong key ok", wrong.optBoolean("ok"))
            assertFalse(name + " wrong key sealed", wrong.optBoolean("unlocked"))
        }
    }

    /* ----------------------------------------------------- imaging (camera) */

    @Test
    fun renderedImagesDecode() = withEngine { vm ->
        val list = vectors.getJSONArray("images")
        assertTrue(list.length() >= 3)
        for (i in 0 until list.length()) {
            val v = list.getJSONObject(i)
            val name = v.getString("name")
            val pgm = parsePgm(resource(v.getString("file")))
            assertEquals(name, v.getInt("width"), pgm.width)
            assertEquals(name, v.getInt("height"), pgm.height)
            val req =
                JSONObject()
                    .put("op", "decode")
                    .put("grayB64", Base64.getEncoder().encodeToString(pgm.data))
                    .put("width", pgm.width)
                    .put("height", pgm.height)
            val r = Engine.callRaw(vm, req)
            assertTrue("$name: ${r.optString("error")}", r.optBoolean("ok"))
            assertEquals(name, v.getString("text"), r.getString("text"))
            val diag = r.getJSONObject("diag")
            assertEquals(name, "63/63", diag.getString("teeth"))
            assertEquals(name, v.getInt("version"), diag.getInt("version"))
            assertEquals(name, v.getString("theme") == "night", diag.getBoolean("inverted"))
            assertTrue(name + " crc", diag.getBoolean("crc"))
        }
    }

    /* ------------------------------------------------------------ the bridge */

    @Test
    fun persianQuotesAndNewlinesSurviveTheBridge() = withEngine { vm ->
        // Exercises jsString escaping and the JNI UTF-8 path: Persian text,
        // embedded quotes, backslashes, a newline and a U+2028 line separator.
        val tricky = "سلام \"دنیا\"\nخط\\دوم ۴۷۱۲ \u2028 end"
        val req =
            JSONObject()
                .put("op", "encode")
                .put("text", tricky)
                .put("ecc", "M")
                .put("scale", 6)
        val r = Engine.callRaw(vm, req)
        assertTrue(r.optString("error"), r.optBoolean("ok"))
        val back = Engine.decodeBitsRaw(vm, r.getString("dataBitsHex"), r.getString("beadsHex"))
        assertTrue(back.optString("error"), back.optBoolean("ok"))
        assertEquals(tricky, back.getString("text"))
    }

    @Test
    fun garbageIsRejectedCleanly() = withEngine { vm ->
        val bad =
            Engine.callRaw(
                vm,
                JSONObject()
                    .put("op", "decode")
                    .put("grayB64", "AAAA")
                    .put("width", 2)
                    .put("height", 2),
            )
        assertFalse(bad.optBoolean("ok"))
        assertTrue(bad.getString("error").isNotEmpty())

        val unknown = Engine.callRaw(vm, JSONObject().put("op", "nope"))
        assertFalse(unknown.optBoolean("ok"))

        val sealedWithoutPass =
            Engine.callRaw(
                vm,
                JSONObject()
                    .put("op", "encode")
                    .put("text", "x")
                    .put("secure", JSONObject().put("iterations", 1000)),
            )
        // A secure block with no key material must fall back to a plain symbol.
        assertTrue(sealedWithoutPass.optString("error"), sealedWithoutPass.optBoolean("ok"))
        assertTrue(sealedWithoutPass.isNull("secure"))
    }
}
